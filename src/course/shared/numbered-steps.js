/* turns progress saved with numbered steps into step ids, once: ticks on steps that no longer exist are
   dropped. The step you were on stays a number, since it only picks where a lesson opens. */
export function numbersToIds(state, table = NUMBERED_STEPS) {
  if (state.stepIds) return state;
  Object.entries(state.inst || {}).forEach(([k, v]) => {
    const steps = {};
    Object.entries(v.steps || {}).forEach(([key, on]) => {
      const [lesson, i] = key.split(":");
      const id = /^\d+$/.test(i) ? table[k] && table[k][lesson] && table[k][lesson][+i] : i;
      if (id) steps[`${lesson}:${id}`] = on;
    });
    v.steps = steps;
  });
  state.stepIds = 1;
  return state;
}
